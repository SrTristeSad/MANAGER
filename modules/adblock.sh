#!/usr/bin/env bash
set -Eeuo pipefail

MANAGER_HOME="${MANAGER_HOME:-/opt/manager}"
MANAGER_ETC="${MANAGER_ETC:-/etc/manager}"
# shellcheck source=/dev/null
source "$MANAGER_HOME/lib/common.sh"
require_root

AD_DIR="$MANAGER_ETC/adblock"
SOURCES="$AD_DIR/sources.list"
WHITELIST="$AD_DIR/whitelist.txt"
BLACKLIST="$AD_DIR/blacklist.txt"
HOSTS="$AD_DIR/hosts"
OWNERSHIP="$AD_DIR/dnsmasq.owner"
CONF="/etc/dnsmasq.d/90-manager-adblock.conf"
STATS_CONF="/etc/dnsmasq.d/91-manager-adblock-stats.conf"
TIMER="/etc/systemd/system/manager-adblock-update.timer"
SERVICE="/etc/systemd/system/manager-adblock-update.service"
DEFAULT_SOURCE="https://raw.githubusercontent.com/StevenBlack/hosts/master/hosts"

is_private_ipv4() {
  local ip="$1" a b
  is_valid_ipv4 "$ip" || return 1
  IFS=. read -r a b _ _ <<< "$ip"
  a=$((10#$a)); b=$((10#$b))
  (( a == 10 )) && return 0
  (( a == 127 )) && return 0
  (( a == 192 && b == 168 )) && return 0
  (( a == 172 && b >= 16 && b <= 31 )) && return 0
  (( a == 100 && b >= 64 && b <= 127 )) && return 0
  return 1
}

is_valid_domain() {
  local d="${1,,}"
  [[ ${#d} -le 253 ]] || return 1
  [[ "$d" =~ ^([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$ ]]
}

init_files() {
  mkdir -p "$AD_DIR"
  if [[ ! -s "$SOURCES" ]]; then
    printf '%s\n' "$DEFAULT_SOURCE" > "$SOURCES"
  fi
  touch "$WHITELIST" "$BLACKLIST" "$HOSTS"
  chmod 0644 "$SOURCES" "$WHITELIST" "$BLACKLIST" "$HOSTS"
}

write_dnsmasq_config() {
  local listen="${1:-127.0.0.1}"
  mkdir -p /etc/dnsmasq.d "$AD_DIR"
  cat > "$CONF" <<EOF
# Managed by MANAGER. Local/VPN use only.
port=53
domain-needed
bogus-priv
stop-dns-rebind
no-resolv
server=1.1.1.1
server=9.9.9.9
cache-size=10000
bind-interfaces
listen-address=$listen
addn-hosts=$HOSTS
EOF
  chmod 0644 "$CONF"
}

blocked_count() {
  awk '!/^#/ && NF {c++} END {print c+0}' "$HOSTS" 2>/dev/null || printf '0\n'
}

normalize_domain_file() {
  local file="$1" tmp
  tmp="$(mktemp)"
  awk '
    BEGIN { IGNORECASE=1 }
    /^[[:space:]]*#/ || /^[[:space:]]*$/ { next }
    {
      d=tolower($1)
      gsub(/\r/, "", d)
      if (d ~ /^([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$/) print d
    }
  ' "$file" | sort -u > "$tmp"
  install -m 0644 "$tmp" "$file"
  rm -f "$tmp"
}

build_hosts() {
  init_files
  normalize_domain_file "$WHITELIST"
  normalize_domain_file "$BLACKLIST"

  local work merged filtered url count=0
  work="$(mktemp -d)"
  merged="$work/domains"
  filtered="$work/filtered"
  : > "$merged"

  while IFS= read -r url || [[ -n "$url" ]]; do
    url="${url%%#*}"
    url="$(printf '%s' "$url" | xargs)"
    [[ -z "$url" ]] && continue
    [[ "$url" =~ ^https?:// ]] || { warn "Ignorando fonte inválida: $url"; continue; }
    count=$((count + 1))
    info "Baixando lista $count..."
    if curl -fsSL --connect-timeout 10 --max-time 90 "$url" -o "$work/list-$count"; then
      awk '
        BEGIN { IGNORECASE=1 }
        /^[[:space:]]*#/ || /^[[:space:]]*$/ { next }
        {
          d=""
          if ($1=="0.0.0.0" || $1=="127.0.0.1" || $1=="::" || $1=="::1") d=$2
          else if (NF==1) d=$1
          gsub(/\r/, "", d)
          sub(/#.*/, "", d)
          d=tolower(d)
          if (d ~ /^([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$/ && d != "localhost.localdomain") print d
        }
      ' "$work/list-$count" >> "$merged"
    else
      warn "Falha ao baixar: $url"
    fi
  done < "$SOURCES"

  cat "$BLACKLIST" >> "$merged"
  sort -u "$merged" -o "$merged"

  if [[ ! -s "$merged" ]]; then
    rm -rf "$work"
    err "Nenhuma lista válida foi obtida. Mantive a lista anterior."
    return 1
  fi

  awk '
    NR==FNR { if ($1!="") white[tolower($1)]=1; next }
    function allowed(d, x,p) {
      x=d
      while (x!="") {
        if (white[x]) return 1
        p=index(x,".")
        if (!p) break
        x=substr(x,p+1)
      }
      return 0
    }
    !allowed(tolower($1)) {print tolower($1)}
  ' "$WHITELIST" "$merged" > "$filtered"

  {
    echo "# Generated by MANAGER - $(date -Is)"
    awk '{print "0.0.0.0 " $1}' "$filtered"
  } > "$work/hosts"

  install -m 0644 "$work/hosts" "$HOSTS"
  local total
  total="$(blocked_count)"
  rm -rf "$work"
  ok "$total domínios bloqueados após whitelist/blacklist"
}

install_timer() {
  cat > "$SERVICE" <<EOF
[Unit]
Description=Update MANAGER DNS ad-block lists
After=network-online.target
Wants=network-online.target

[Service]
Type=oneshot
ExecStart=$MANAGER_HOME/modules/adblock.sh --update-quiet
EOF

  cat > "$TIMER" <<'EOF'
[Unit]
Description=Daily MANAGER DNS ad-block update

[Timer]
OnCalendar=daily
RandomizedDelaySec=45m
Persistent=true

[Install]
WantedBy=timers.target
EOF
  systemctl daemon-reload
  systemctl enable --now manager-adblock-update.timer >/dev/null 2>&1
}

record_dnsmasq_ownership() {
  mkdir -p "$AD_DIR"
  [[ -f "$OWNERSHIP" ]] && return 0
  if dpkg-query -W -f='${Status}' dnsmasq 2>/dev/null | grep -q 'install ok installed'; then
    echo "preexisting" > "$OWNERSHIP"
  else
    echo "manager" > "$OWNERSHIP"
  fi
  chmod 0600 "$OWNERSHIP"
}

install_adblock() {
  header
  say "${C_WHITE}INSTALAR BLOQUEIO DE ANÚNCIOS DNS${C_RESET}\n"
  info "O DNS será ligado somente em 127.0.0.1 inicialmente."
  info "Depois você pode selecionar um IP privado da VPN/rede."
  confirm "Continuar?" || return

  record_dnsmasq_ownership
  export DEBIAN_FRONTEND=noninteractive
  apt-get update -y
  apt-get install -y dnsmasq curl ca-certificates
  init_files
  write_dnsmasq_config "127.0.0.1"
  build_hosts

  if ! dnsmasq --test >/dev/null 2>&1; then
    err "A configuração do dnsmasq falhou no teste."
    dnsmasq --test || true
    pause
    return
  fi

  systemctl enable dnsmasq >/dev/null 2>&1 || true
  if ! systemctl restart dnsmasq; then
    err "dnsmasq não iniciou. Provavelmente outro serviço ocupa a porta 53."
    ss -lntup 2>/dev/null | grep ':53 ' || true
    pause
    return
  fi
  install_timer
  ok "Bloqueador instalado"
  pause
}

update_lists() {
  local quiet="${1:-no}"
  [[ -f "$CONF" ]] || { [[ "$quiet" == yes ]] || err "Bloqueador ainda não está instalado"; return 1; }
  build_hosts || return 1
  dnsmasq --test >/dev/null 2>&1 || return 1
  systemctl reload-or-restart dnsmasq
  [[ "$quiet" == yes ]] || pause
}

configure_listen() {
  header
  [[ -f "$CONF" ]] || { err "Instale o bloqueador primeiro"; pause; return; }
  say "${C_WHITE}ENDEREÇO DO DNS${C_RESET}\n"
  say "IPs IPv4 disponíveis:"
  say "  127.0.0.1 (somente servidor)"
  ip -o -4 addr show scope global | awk '{print "  " $2 " -> " $4}' || true
  say ""
  warn "Por segurança, o MANAGER aceita apenas loopback, RFC1918 e CGNAT/VPN."
  local addr
  read -r -p "IP para o dnsmasq: " addr
  if ! is_private_ipv4 "$addr"; then
    err "Use um endereço privado/VPN válido. DNS público aberto não é permitido por este módulo."
    pause
    return
  fi
  if [[ "$addr" != "127.0.0.1" ]] && ! ip -o -4 addr show | awk '{print $4}' | cut -d/ -f1 | grep -Fxq "$addr"; then
    err "Esse IP não está atribuído ao servidor"
    pause
    return
  fi

  sed -i "s/^listen-address=.*/listen-address=$addr/" "$CONF"
  if dnsmasq --test >/dev/null 2>&1 && systemctl restart dnsmasq; then
    ok "DNS escutando em $addr:53"
  else
    err "Não foi possível iniciar nesse endereço. Revertendo para 127.0.0.1."
    sed -i 's/^listen-address=.*/listen-address=127.0.0.1/' "$CONF"
    systemctl restart dnsmasq || true
  fi
  pause
}

show_status() {
  header
  say "${C_WHITE}STATUS DO BLOQUEIO DNS${C_RESET}\n"
  if [[ ! -f "$CONF" ]]; then
    warn "Não instalado"
    pause
    return
  fi
  local listen total updated white black
  listen="$(awk -F= '/^listen-address=/ {print $2}' "$CONF")"
  total="$(blocked_count)"
  white="$(awk 'NF&&!/^#/ {c++} END{print c+0}' "$WHITELIST" 2>/dev/null || echo 0)"
  black="$(awk 'NF&&!/^#/ {c++} END{print c+0}' "$BLACKLIST" 2>/dev/null || echo 0)"
  updated="$(stat -c '%y' "$HOSTS" 2>/dev/null | cut -d. -f1 || echo '-')"
  printf '%-20s %s\n' "dnsmasq:" "$(systemctl is-active dnsmasq 2>/dev/null || true)"
  printf '%-20s %s\n' "Endereço:" "$listen:53"
  printf '%-20s %s\n' "Domínios:" "$total"
  printf '%-20s %s\n' "Whitelist manual:" "$white"
  printf '%-20s %s\n' "Blacklist manual:" "$black"
  printf '%-20s %s\n' "Última atualização:" "$updated"
  printf '%-20s %s\n' "Timer:" "$(systemctl is-active manager-adblock-update.timer 2>/dev/null || true)"
  printf '%-20s %s\n' "Estatísticas:" "$([[ -f "$STATS_CONF" ]] && echo ativas || echo desativadas)"
  say "\nPorta 53:"
  ss -lntup 2>/dev/null | grep ':53 ' || true
  pause
}

manage_sources() {
  init_files
  while true; do
    header
    say "${C_WHITE}FONTES DE BLOQUEIO${C_RESET}\n"
    nl -ba "$SOURCES"
    say "\n 1) Adicionar fonte"
    say " 2) Remover fonte"
    say " 3) Restaurar padrão"
    say " 0) Voltar"
    read -r -p "Opção: " op
    case "$op" in
      1)
        local url
        read -r -p "URL HTTPS/HTTP: " url
        if [[ "$url" =~ ^https?:// ]]; then
          printf '%s\n' "$url" >> "$SOURCES"
          ok "Fonte adicionada"
        else
          err "URL inválida"
        fi
        pause
        ;;
      2)
        local n tmp
        read -r -p "Número da fonte: " n
        [[ "$n" =~ ^[0-9]+$ ]] || { err "Número inválido"; pause; continue; }
        tmp="$(mktemp)"
        awk -v n="$n" 'NR != n {print}' "$SOURCES" > "$tmp"
        install -m 0644 "$tmp" "$SOURCES"
        rm -f "$tmp"
        ;;
      3)
        printf '%s\n' "$DEFAULT_SOURCE" > "$SOURCES"
        ok "Fonte padrão restaurada"
        pause
        ;;
      0) return ;;
      *) warn "Opção inválida"; sleep 1 ;;
    esac
  done
}

remove_domain_line() {
  local file="$1" domain="$2" tmp
  tmp="$(mktemp)"
  awk -v d="${domain,,}" 'tolower($1)!=d {print}' "$file" > "$tmp"
  install -m 0644 "$tmp" "$file"
  rm -f "$tmp"
}

manage_manual_lists() {
  init_files
  while true; do
    header
    say "${C_WHITE}WHITELIST / BLACKLIST MANUAL${C_RESET}\n"
    say "Whitelist:"
    sed 's/^/  /' "$WHITELIST" | sed -n '1,30p'
    say "\nBlacklist:"
    sed 's/^/  /' "$BLACKLIST" | sed -n '1,30p'
    say "\n 1) Adicionar à whitelist"
    say " 2) Remover da whitelist"
    say " 3) Adicionar à blacklist"
    say " 4) Remover da blacklist"
    say " 5) Recompilar listas agora"
    say " 0) Voltar"
    read -r -p "Opção: " op
    case "$op" in
      1|2|3|4)
        local domain file
        read -r -p "Domínio (ex.: ads.example.com): " domain
        domain="${domain,,}"
        is_valid_domain "$domain" || { err "Domínio inválido"; pause; continue; }
        if [[ "$op" == 1 || "$op" == 2 ]]; then file="$WHITELIST"; else file="$BLACKLIST"; fi
        if [[ "$op" == 1 || "$op" == 3 ]]; then
          grep -Fxiq "$domain" "$file" || printf '%s\n' "$domain" >> "$file"
          normalize_domain_file "$file"
          ok "Domínio adicionado"
        else
          remove_domain_line "$file" "$domain"
          ok "Domínio removido"
        fi
        pause
        ;;
      5)
        if [[ -f "$CONF" ]]; then
          build_hosts && systemctl reload-or-restart dnsmasq
        else
          build_hosts
        fi
        pause
        ;;
      0) return ;;
      *) warn "Opção inválida"; sleep 1 ;;
    esac
  done
}

toggle_stats() {
  header
  [[ -f "$CONF" ]] || { err "Instale o bloqueador primeiro"; pause; return; }
  if [[ -f "$STATS_CONF" ]]; then
    confirm "Desativar log de consultas DNS?" || return
    rm -f "$STATS_CONF"
    systemctl restart dnsmasq
    ok "Estatísticas de consultas desativadas"
  else
    warn "Este recurso registra nomes de domínio consultados no journal do sistema."
    warn "Isso pode conter informações privadas de navegação dos clientes da VPN."
    confirm "Ativar mesmo assim?" || return
    cat > "$STATS_CONF" <<'EOF'
# Optional query logging for MANAGER statistics.
log-queries=extra
EOF
    chmod 0644 "$STATS_CONF"
    dnsmasq --test >/dev/null
    systemctl restart dnsmasq
    ok "Estatísticas ativadas"
  fi
  pause
}

show_query_stats() {
  header
  say "${C_WHITE}ESTATÍSTICAS DNS - HOJE${C_RESET}\n"
  [[ -f "$STATS_CONF" ]] || { warn "Ative as estatísticas primeiro"; pause; return; }
  local blocked queries
  queries="$(journalctl -u dnsmasq --since today --no-pager 2>/dev/null | grep -c ' query\[' || true)"
  blocked="$(journalctl -u dnsmasq --since today --no-pager 2>/dev/null | grep -Ec ' config .* is 0\.0\.0\.0' || true)"
  printf '%-24s %s\n' "Consultas registradas:" "$queries"
  printf '%-24s %s\n' "Respostas bloqueadas:" "$blocked"
  say "\nTop domínios bloqueados:"
  journalctl -u dnsmasq --since today --no-pager 2>/dev/null \
    | sed -n 's/.* config \([^ ]*\) is 0\.0\.0\.0.*/\1/p' \
    | sort | uniq -c | sort -nr | head -n 15 || true
  pause
}

remove_adblock() {
  header
  confirm "Remover a configuração de bloqueio DNS do MANAGER?" || return
  local owner="manager"
  [[ -f "$OWNERSHIP" ]] && owner="$(cat "$OWNERSHIP")"

  systemctl disable --now manager-adblock-update.timer >/dev/null 2>&1 || true
  rm -f "$TIMER" "$SERVICE" "$CONF" "$STATS_CONF"
  systemctl daemon-reload

  if [[ "$owner" == "preexisting" ]]; then
    systemctl restart dnsmasq 2>/dev/null || true
  else
    systemctl disable --now dnsmasq >/dev/null 2>&1 || true
  fi
  rm -rf "$AD_DIR"
  ok "Configuração removida. O pacote dnsmasq foi mantido para evitar remoções destrutivas."
  pause
}

if [[ "${1:-}" == "--update-quiet" ]]; then
  update_lists yes
  exit $?
fi

while true; do
  header
  say "${C_WHITE}BLOQUEIO DE ANÚNCIOS DNS${C_RESET}\n"
  say " 1) Instalar/configurar"
  say " 2) Atualizar listas agora"
  say " 3) Escolher IP privado/VPN do DNS"
  say " 4) Gerenciar fontes"
  say " 5) Whitelist / blacklist manual"
  say " 6) Status"
  say " 7) Ativar/desativar estatísticas"
  say " 8) Ver estatísticas de hoje"
  say " 9) Remover configuração"
  say " 0) Voltar"
  say ""
  read -r -p "Opção: " opt
  case "$opt" in
    1) install_adblock ;;
    2) update_lists no ;;
    3) configure_listen ;;
    4) manage_sources ;;
    5) manage_manual_lists ;;
    6) show_status ;;
    7) toggle_stats ;;
    8) show_query_stats ;;
    9) remove_adblock ;;
    0) exit 0 ;;
    *) warn "Opção inválida"; sleep 1 ;;
  esac
done
