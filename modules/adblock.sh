#!/usr/bin/env bash
set -Eeuo pipefail

MANAGER_HOME="${MANAGER_HOME:-/opt/manager}"
MANAGER_ETC="${MANAGER_ETC:-/etc/manager}"
# shellcheck source=/dev/null
source "$MANAGER_HOME/lib/common.sh"
require_root

AD_DIR="$MANAGER_ETC/adblock"
SOURCES="$AD_DIR/sources.list"
HOSTS="$AD_DIR/hosts"
CONF="/etc/dnsmasq.d/90-manager-adblock.conf"
TIMER="/etc/systemd/system/manager-adblock-update.timer"
SERVICE="/etc/systemd/system/manager-adblock-update.service"
DEFAULT_SOURCE="https://raw.githubusercontent.com/StevenBlack/hosts/master/hosts"

is_private_ipv4() {
  local ip="$1" a b
  is_valid_ipv4 "$ip" || return 1
  IFS=. read -r a b _ _ <<< "$ip"
  (( a == 10 )) && return 0
  (( a == 127 )) && return 0
  (( a == 192 && b == 168 )) && return 0
  (( a == 172 && b >= 16 && b <= 31 )) && return 0
  (( a == 100 && b >= 64 && b <= 127 )) && return 0
  return 1
}

write_default_sources() {
  mkdir -p "$AD_DIR"
  if [[ ! -s "$SOURCES" ]]; then
    printf '%s\n' "$DEFAULT_SOURCE" > "$SOURCES"
    chmod 0644 "$SOURCES"
  fi
}

write_dnsmasq_config() {
  local listen="${1:-127.0.0.1}"
  mkdir -p /etc/dnsmasq.d "$AD_DIR"
  cat > "$CONF" <<EOF
# Managed by MANAGER. Local/VPN use only.
port=53
domain-needed
bogus-priv
stop-dns-rebind
no-resolv
server=1.1.1.1
server=9.9.9.9
cache-size=10000
bind-interfaces
listen-address=$listen
addn-hosts=$HOSTS
EOF
  chmod 0644 "$CONF"
}

build_hosts() {
  write_default_sources
  local work merged url count=0
  work="$(mktemp -d)"
  merged="$work/domains"
  : > "$merged"

  while IFS= read -r url || [[ -n "$url" ]]; do
    url="${url%%#*}"
    url="$(printf '%s' "$url" | xargs)"
    [[ -z "$url" ]] && continue
    [[ "$url" =~ ^https?:// ]] || { warn "Ignorando fonte inválida: $url"; continue; }
    count=$((count + 1))
    info "Baixando lista $count..."
    if curl -fsSL --connect-timeout 10 --max-time 90 "$url" -o "$work/list-$count"; then
      awk '
        BEGIN { IGNORECASE=1 }
        /^[[:space:]]*#/ || /^[[:space:]]*$/ { next }
        {
          d=""
          if ($1=="0.0.0.0" || $1=="127.0.0.1" || $1=="::" || $1=="::1") d=$2
          else if (NF==1) d=$1
          gsub(/\r/, "", d)
          sub(/#.*/, "", d)
          if (d ~ /^([a-z0-9_-]+\.)+[a-z0-9-]+$/ && d != "localhost" && d != "localhost.localdomain") print tolower(d)
        }
      ' "$work/list-$count" >> "$merged"
    else
      warn "Falha ao baixar: $url"
    fi
  done < "$SOURCES"

  if [[ ! -s "$merged" ]]; then
    rm -rf "$work"
    err "Nenhuma lista válida foi obtida. Mantive a lista anterior."
    return 1
  fi

  sort -u "$merged" -o "$merged"
  {
    echo "# Generated by MANAGER - $(date -Is)"
    awk '{print "0.0.0.0 " $1}' "$merged"
  } > "$work/hosts"

  install -m 0644 "$work/hosts" "$HOSTS"
  local total
  total="$(grep -cv '^#' "$HOSTS" || true)"
  rm -rf "$work"
  ok "$total domínios carregados"
}

install_timer() {
  cat > "$SERVICE" <<EOF
[Unit]
Description=Update MANAGER DNS ad-block lists
After=network-online.target
Wants=network-online.target

[Service]
Type=oneshot
ExecStart=$MANAGER_HOME/modules/adblock.sh --update-quiet
EOF

  cat > "$TIMER" <<'EOF'
[Unit]
Description=Daily MANAGER DNS ad-block update

[Timer]
OnCalendar=daily
RandomizedDelaySec=45m
Persistent=true

[Install]
WantedBy=timers.target
EOF
  systemctl daemon-reload
  systemctl enable --now manager-adblock-update.timer >/dev/null 2>&1
}

install_adblock() {
  header
  say "${C_WHITE}INSTALAR BLOQUEIO DE ANÚNCIOS DNS${C_RESET}\n"
  info "O DNS será ligado somente em 127.0.0.1 inicialmente."
  info "Depois você pode selecionar um IP privado da VPN/rede."
  confirm "Continuar?" || return

  export DEBIAN_FRONTEND=noninteractive
  apt-get update -y
  apt-get install -y dnsmasq curl ca-certificates
  mkdir -p "$AD_DIR"
  write_default_sources
  : > "$HOSTS"
  write_dnsmasq_config "127.0.0.1"
  build_hosts

  if ! dnsmasq --test >/dev/null 2>&1; then
    err "A configuração do dnsmasq falhou no teste."
    dnsmasq --test || true
    pause
    return
  fi

  systemctl enable dnsmasq >/dev/null 2>&1 || true
  if ! systemctl restart dnsmasq; then
    err "dnsmasq não iniciou. Provavelmente outro serviço ocupa a porta 53."
    ss -lntup 2>/dev/null | grep ':53 ' || true
    pause
    return
  fi
  install_timer
  ok "Bloqueador instalado"
  pause
}

update_lists() {
  local quiet="${1:-no}"
  [[ -f "$CONF" ]] || { [[ "$quiet" == yes ]] || err "Bloqueador ainda não está instalado"; return 1; }
  build_hosts || return 1
  dnsmasq --test >/dev/null 2>&1 || return 1
  systemctl reload-or-restart dnsmasq
  [[ "$quiet" == yes ]] || pause
}

configure_listen() {
  header
  [[ -f "$CONF" ]] || { err "Instale o bloqueador primeiro"; pause; return; }
  say "${C_WHITE}ENDEREÇO DO DNS${C_RESET}\n"
  say "IPs IPv4 disponíveis:"
  say "  127.0.0.1 (somente servidor)"
  ip -o -4 addr show scope global | awk '{print "  " $2 " -> " $4}' || true
  say ""
  warn "Por segurança, o MANAGER aceita apenas loopback, RFC1918 e CGNAT/VPN."
  local addr
  read -r -p "IP para o dnsmasq: " addr
  if ! is_private_ipv4 "$addr"; then
    err "Use um endereço privado/VPN válido. DNS público aberto não é permitido por este módulo."
    pause
    return
  fi
  if [[ "$addr" != "127.0.0.1" ]] && ! ip -o -4 addr show | awk '{print $4}' | cut -d/ -f1 | grep -Fxq "$addr"; then
    err "Esse IP não está atribuído ao servidor"
    pause
    return
  fi

  sed -i "s/^listen-address=.*/listen-address=$addr/" "$CONF"
  if dnsmasq --test >/dev/null 2>&1 && systemctl restart dnsmasq; then
    ok "DNS escutando em $addr:53"
  else
    err "Não foi possível iniciar nesse endereço. Revertendo para 127.0.0.1."
    sed -i 's/^listen-address=.*/listen-address=127.0.0.1/' "$CONF"
    systemctl restart dnsmasq || true
  fi
  pause
}

show_status() {
  header
  say "${C_WHITE}STATUS DO BLOQUEIO DNS${C_RESET}\n"
  if [[ ! -f "$CONF" ]]; then
    warn "Não instalado"
    pause
    return
  fi
  local listen total updated
  listen="$(awk -F= '/^listen-address=/ {print $2}' "$CONF")"
  total="$(grep -cv '^#' "$HOSTS" 2>/dev/null || echo 0)"
  updated="$(stat -c '%y' "$HOSTS" 2>/dev/null | cut -d. -f1 || echo '-')"
  printf '%-20s %s\n' "dnsmasq:" "$(systemctl is-active dnsmasq 2>/dev/null || true)"
  printf '%-20s %s\n' "Endereço:" "$listen:53"
  printf '%-20s %s\n' "Domínios:" "$total"
  printf '%-20s %s\n' "Última atualização:" "$updated"
  printf '%-20s %s\n' "Timer:" "$(systemctl is-active manager-adblock-update.timer 2>/dev/null || true)"
  say "\nPorta 53:"
  ss -lntup 2>/dev/null | grep ':53 ' || true
  pause
}

manage_sources() {
  write_default_sources
  while true; do
    header
    say "${C_WHITE}FONTES DE BLOQUEIO${C_RESET}\n"
    nl -ba "$SOURCES"
    say "\n 1) Adicionar fonte"
    say " 2) Remover fonte"
    say " 3) Restaurar padrão"
    say " 0) Voltar"
    read -r -p "Opção: " op
    case "$op" in
      1)
        local url
        read -r -p "URL HTTPS/HTTP: " url
        if [[ "$url" =~ ^https?:// ]]; then
          printf '%s\n' "$url" >> "$SOURCES"
          ok "Fonte adicionada"
        else
          err "URL inválida"
        fi
        pause
        ;;
      2)
        local n tmp
        read -r -p "Número da fonte: " n
        [[ "$n" =~ ^[0-9]+$ ]] || { err "Número inválido"; pause; continue; }
        tmp="$(mktemp)"
        awk -v n="$n" 'NR != n {print}' "$SOURCES" > "$tmp"
        install -m 0644 "$tmp" "$SOURCES"
        rm -f "$tmp"
        ;;
      3)
        printf '%s\n' "$DEFAULT_SOURCE" > "$SOURCES"
        ok "Fonte padrão restaurada"
        pause
        ;;
      0) return ;;
      *) warn "Opção inválida"; sleep 1 ;;
    esac
  done
}

remove_adblock() {
  header
  confirm "Remover a configuração de bloqueio DNS do MANAGER?" || return
  systemctl disable --now manager-adblock-update.timer >/dev/null 2>&1 || true
  rm -f "$TIMER" "$SERVICE" "$CONF"
  rm -rf "$AD_DIR"
  systemctl daemon-reload
  if command_exists dnsmasq; then systemctl restart dnsmasq 2>/dev/null || systemctl stop dnsmasq 2>/dev/null || true; fi
  ok "Configuração removida. O pacote dnsmasq foi mantido para não quebrar outros serviços."
  pause
}

if [[ "${1:-}" == "--update-quiet" ]]; then
  update_lists yes
  exit $?
fi

while true; do
  header
  say "${C_WHITE}BLOQUEIO DE ANÚNCIOS DNS${C_RESET}\n"
  say " 1) Instalar/configurar"
  say " 2) Atualizar listas agora"
  say " 3) Escolher IP privado/VPN do DNS"
  say " 4) Gerenciar fontes"
  say " 5) Status"
  say " 6) Remover configuração"
  say " 0) Voltar"
  say ""
  read -r -p "Opção: " opt
  case "$opt" in
    1) install_adblock ;;
    2) update_lists no ;;
    3) configure_listen ;;
    4) manage_sources ;;
    5) show_status ;;
    6) remove_adblock ;;
    0) exit 0 ;;
    *) warn "Opção inválida"; sleep 1 ;;
  esac
done
